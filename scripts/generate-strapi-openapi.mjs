// Generates Strapi API types from a local OpenAPI export without changing the CMS.
import { readFile, writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const input =
  process.argv.slice(2).find((argument) => !argument.startsWith("--")) ??
  fileURLToPath(new URL("../astro/src/server/content/generated/specification.json", import.meta.url));
const spec = JSON.parse(await readFile(input, "utf8"));
if (spec.openapi !== "3.1.0" || !spec.paths || spec["x-powered-by"] !== "strapi") {
  throw new Error("Expected an OpenAPI 3.1 specification generated by Strapi");
}

/** Remove Strapi's current-time defaults from publishedAt schemas to make generated types stable.
 * @param value A node in the exported OpenAPI specification.
 * @returns Nothing; only volatile timestamp defaults are removed in memory.
 */
function removeVolatileDefaults(value) {
  if (!value || typeof value !== "object") {
    return;
  }
  if (!Array.isArray(value) && value.publishedAt && typeof value.publishedAt === "object") {
    const schema = value.publishedAt;
    if (typeof schema.default === "string" && /^\d{4}-\d{2}-\d{2}T/.test(schema.default)) {
      delete schema.default;
    }
  }
  for (const child of Object.values(value)) {
    removeVolatileDefaults(child);
  }
}

removeVolatileDefaults(spec);
const temporary = await mkdtemp(join(tmpdir(), "aascmed-openapi-"));
const output = fileURLToPath(
  new URL("../astro/src/server/content/generated/types.d.ts", import.meta.url),
);
try {
  const normalized = join(temporary, "strapi-openapi.json");
  const generated = join(temporary, "strapi-openapi.d.ts");
  await writeFile(normalized, JSON.stringify(spec));
  const generator = fileURLToPath(
    new URL("../node_modules/openapi-typescript/bin/cli.js", import.meta.url),
  );
  const result = spawnSync(process.execPath, [generator, normalized, "-o", generated], {
    stdio: "inherit",
  });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(`openapi-typescript exited with ${result.status}`);
  }
  const content =
    "// Types for the Strapi Content API, generated from its OpenAPI specification.\n" +
    (await readFile(generated, "utf8"));
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== content) {
      throw new Error("Generated Strapi API types are out of date");
    }
  } else {
    await writeFile(output, content);
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
