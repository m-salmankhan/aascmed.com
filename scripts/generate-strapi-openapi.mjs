// Generates Strapi API types from a committed export or an explicitly requested live schema refresh.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString, COMMENT_HEADER } from "openapi-typescript";
import { fileURLToPath } from "node:url";
const args = process.argv.slice(2);
const refreshIndex = args.indexOf("--refresh");
const committedSpec = fileURLToPath(
  new URL("../astro/src/server/content/generated/specification.json", import.meta.url),
);
/** Download a CMS build's exported schema for an explicit refresh.
 * @param source Absolute URL of the CMS OpenAPI JSON endpoint.
 * @returns The exported JSON text; HTTP failures and timeouts throw before files change.
 */
async function fetchSpecification(source) {
  if (!source || source.startsWith("--")) {
    throw new Error("Usage: yarn strapi:types --refresh https://your-cms/openapi.json");
  }
  const url = new URL(source);
  if (!["https:", "http:"].includes(url.protocol) || url.username || url.password) {
    throw new Error("The schema URL must use HTTP or HTTPS without embedded credentials");
  }
  const response = await fetch(url, { cache: "no-store", signal: AbortSignal.timeout(15000) });
  if (!response.ok) {
    throw new Error(`OpenAPI download failed with HTTP ${response.status}`);
  }
  return response.text();
}
const input = args.find((argument) => !argument.startsWith("--")) ?? committedSpec;
const sourceText =
  refreshIndex >= 0
    ? await fetchSpecification(args[refreshIndex + 1])
    : await readFile(input, "utf8");
const spec = JSON.parse(sourceText);
if (spec.openapi !== "3.1.0" || !spec.paths || spec["x-powered-by"] !== "strapi") {
  throw new Error("Expected an OpenAPI 3.1 specification generated by Strapi");
}
/** Remove Strapi's current-time defaults from publishedAt schemas to make generated types stable.
 * @param value A node in the exported OpenAPI specification.
 * @returns Nothing; only volatile timestamp defaults are removed in memory.
 */
function removeVolatileDefaults(value) {
  if (!value || typeof value !== "object") {
    return;
  }
  if (!Array.isArray(value) && value.publishedAt && typeof value.publishedAt === "object") {
    const schema = value.publishedAt;
    if (typeof schema.default === "string" && /^\d{4}-\d{2}-\d{2}T/.test(schema.default)) {
      delete schema.default;
    }
  }
  for (const child of Object.values(value)) {
    removeVolatileDefaults(child);
  }
}
removeVolatileDefaults(spec);
const output = fileURLToPath(
  new URL("../astro/src/server/content/generated/types.d.ts", import.meta.url),
);
const content =
  "// Types for the Strapi Content API, generated from its OpenAPI specification.\n" +
  COMMENT_HEADER +
  astToString(await openapiTS(spec));
if (args.includes("--check")) {
  if ((await readFile(output, "utf8")) !== content) {
    throw new Error("Generated Strapi API types are out of date");
  }
} else {
  await writeFile(output, content);
  if (refreshIndex >= 0) {
    await writeFile(committedSpec, sourceText);
  }
}
