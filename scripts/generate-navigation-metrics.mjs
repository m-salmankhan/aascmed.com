// Build-only font shaping. No browser installation or client measurement is needed.
import { createCanvas, GlobalFonts } from '@napi-rs/canvas';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { navigationItems, navigationSizing } from '../src/components/header/navigation-config.mts';

const fontPath = fileURLToPath(new URL('../src/server/media/assets/Poppins-ExtraBold.ttf', import.meta.url));
const output = new URL('../src/components/header/generated-navigation-metrics.mts', import.meta.url);

/** Derive CSS widths from the exact labels, bundled font, letter spacing and gaps.
 * Canvas measures glyph advances; CSS letter spacing is added once per character.
 */
export function measureNavigation(items = navigationItems, sizing = navigationSizing) {
  if (!GlobalFonts.registerFromPath(fontPath, 'AASC Navigation Measurement')) throw new Error('Cannot register navigation font');
  const referenceRoot = 100;
  const context = createCanvas(1, 1).getContext('2d');
  context.font = `800 ${referenceRoot * sizing.fontSize}px "AASC Navigation Measurement"`;
  const itemWidthsRem = items.map(item => Math.ceil((context.measureText(item.label).width / referenceRoot
    + Array.from(item.label).length * sizing.letterSpacing + sizing.fitAllowance / items.length) * 100) / 100);
  const rowWidth = itemWidthsRem.reduce((sum, width) => sum + width, 0) + (items.length - 1) * sizing.linkGap;
  const rowWidthRem = Math.ceil(rowWidth * 100) / 100;
  const rightWidthRem = Math.ceil((rowWidthRem + sizing.logoWidth + sizing.headerGap) * 100) / 100;
  return { rowWidthRem, rightWidthRem, itemWidthsRem };
}

/** Regenerate the imported CSS constant whenever Astro loads its configuration. */
export async function generateNavigationMetrics() {
  const metrics = measureNavigation();
  const contents = `// Generated by scripts/generate-navigation-metrics.mjs; do not edit.\n/** Required menu width in rem, including the font-shaping allowance. */\nexport const navigationRowWidthRem = ${metrics.rowWidthRem};\n/** Required width for the logo, gap and full menu on one row. */\nexport const navigationRightWidthRem = ${metrics.rightWidthRem};\n/** Stable per-link slots prevent font loading from moving the menu. */\nexport const navigationItemWidthsRem = ${JSON.stringify(metrics.itemWidthsRem)} as const;\n`;
  if (await readFile(output, 'utf8').catch(() => '') !== contents) {
    await mkdir(new URL('../src/components/header/', import.meta.url), { recursive: true });
    await writeFile(output, contents);
  }
  return metrics;
}
