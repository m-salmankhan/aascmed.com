// Checks rendered Astro metadata, tracking, sitemaps and assets using local fixtures.
import assert from 'node:assert/strict';
import test from 'node:test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { readFile, stat, writeFile, unlink } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { startFixtureCms, fixtureToken } from '../fixtures/astro-cms/server.mjs';
const astroRoot = fileURLToPath(new URL('../../astro/', import.meta.url));
const staticOutputDir = path.join(astroRoot, 'dist-static');
/** Check real build output for legacy sitemap fields and truthful CMS edit dates.
 * @param xml XML generated by Astro's sitemap integration.
 * @returns Nothing; missing metadata or invented edit dates fail the test.
 */
function assertSitemapMetadata(xml) {
  const modified = xml.match(
    /<url><loc>https:\/\/www\.aascmed\.com\/blog\/modified-blog\/<\/loc>([\s\S]*?)<\/url>/,
  )?.[1];
  assert.ok(modified, 'published CMS routes appear in the sitemap');
  assert.ok(modified.includes('<lastmod>2026-04-03T14:20:00.000Z</lastmod>'));
  assert.ok(modified.includes('<changefreq>daily</changefreq>'));
  assert.ok(modified.includes('<priority>0.7</priority>'));
  const undated = xml.match(
    /<url><loc>https:\/\/www\.aascmed\.com\/blog\/undated-blog\/<\/loc>([\s\S]*?)<\/url>/,
  )?.[1];
  assert.ok(undated);
  assert.ok(
    !undated.includes('<lastmod>'),
    'publication date is not substituted for modification time',
  );
}
test(
  'Astro static and SSR documents preserve metadata, tracking, sitemaps and assets',
  { timeout: 120000 },
  async () => {
    const cms = await startFixtureCms();
    const cmsUrl = cms.origin;
    const observedCmsRequests = cms.requests;
    cms.published.blogs.push({
      ...structuredClone(cms.published.blogs[0]),
      documentId: 'modified-blog',
      slug: 'modified-blog',
      title: 'Modified post',
    });
    const undatedBlog = {
      ...structuredClone(cms.published.blogs[1]),
      documentId: 'undated-blog',
      slug: 'undated-blog',
      title: 'Post without an edit date',
    };
    delete undatedBlog.updatedAt;
    cms.published.blogs.push(undatedBlog);
    /** Build one Astro target against the test's local CMS fixture.
     * @param config Static or SSR Astro configuration filename, relative to the Astro package.
     * @returns A promise that resolves when the child build succeeds; rejects on spawn or build failure.
     */
    async function runBuild(config) {
      await new Promise((resolve, reject) => {
        const child = spawn(
          process.execPath,
          ['node_modules/astro/bin/astro.mjs', 'build', '--config', config],
          {
            env: {
              ...process.env,
              GATSBY_STRAPI_API_URL: cmsUrl,
              STRAPI_TOKEN: fixtureToken,
              ASTRO_CONTENT_MODE: 'published',
              STRAPI_MEDIA_ORIGINS: cmsUrl,
              PUBLIC_MAPBOX_API_KEY: '',
              GATSBY_MAPBOX_API_KEY: '',
            },
            cwd: astroRoot,
            stdio: 'inherit',
          },
        );
        child.once('error', reject);
        child.once('exit', (code) =>
          code === 0 ? resolve() : reject(new Error(`${config} failed with exit ${code}`)),
        );
      });
    }
    let app;
    const fixturePath = new URL(
      '../../astro/src/pages/verification-document-fixture.astro',
      import.meta.url,
    );
    let fixtureCreated = false;
    const trackingFixtures = [];
    const trackingCases = [
      {
        name: 'analytics-only',
        enabled: true,
        settings: { googleAnalyticsId: 'G-ONLY', googleTagManagerId: '', pixelId: '' },
      },
      {
        name: 'tag-manager-only',
        enabled: true,
        settings: { googleAnalyticsId: '', googleTagManagerId: 'GTM-ONLY', pixelId: '' },
      },
      {
        name: 'tracking-disabled',
        enabled: false,
        settings: {
          googleAnalyticsId: 'G-DISABLED',
          googleTagManagerId: 'GTM-DISABLED',
          pixelId: '',
        },
      },
    ];
    try {
      await writeFile(
        fixturePath,
        `---
import SiteDocument from '../layouts/SiteDocument.astro';
---
<SiteDocument title="Metadata fixture" description="Fixture description" pathname="/verification-document-fixture/"
  useTracking={true} trackingSettings={{ googleAnalyticsId: 'G-TEST', googleTagManagerId: 'GTM-TEST', pixelId: 'TEST-PIXEL' }}
  socialImagePath="/og-images/fixture.jpg" structuredData={{ '@type': 'MedicalClinic', name: '</script><script>untrusted</script>' }}>
  <main>Document fixture</main>
</SiteDocument>`,
        { flag: 'wx' },
      );
      fixtureCreated = true;
      for (const trackingCase of trackingCases) {
        const file = new URL(`../../astro/src/pages/${trackingCase.name}.astro`, import.meta.url);
        await writeFile(
          file,
          `---
import SiteDocument from '../layouts/SiteDocument.astro';
---
<SiteDocument pathname="/${trackingCase.name}/" useTracking={${trackingCase.enabled}}
  trackingSettings={${JSON.stringify(trackingCase.settings)}}>
  <main>Tracking fixture</main>
</SiteDocument>`,
          { flag: 'wx' },
        );
        trackingFixtures.push(file);
      }
      await runBuild('astro.config.static.ts');
      assert.ok(
        observedCmsRequests.length >= 5,
        'static sitemap loads its published route collections',
      );
      assert.ok(
        observedCmsRequests.every((url) => url.query.status === 'published'),
        'static build requests published content only',
      );
      const homeHtml = await readFile(path.join(staticOutputDir, 'index.html'), 'utf8');
      assert.ok(
        homeHtml.includes('PUBLISHED HERO'),
        'the real homepage replaces the retired architecture proof',
      );
      const fixtureHtml = await readFile(
        path.join(staticOutputDir, 'verification-document-fixture/index.html'),
        'utf8',
      );
      for (const expected of [
        '<title>Metadata fixture | Allergy, Asthma and Sinus Centers</title>',
        'href="https://www.aascmed.com/verification-document-fixture/"',
        'property="og:title"',
        'type="application/ld+json"',
        '"@type":"MedicalClinic"',
        'name="twitter:card"',
        'https://fonts.googleapis.com/css2?family=Poppins:wght@300;800&display=swap',
      ]) {
        assert.ok(fixtureHtml.includes(expected), `static HTML missing ${expected}`);
      }
      assert.ok(!fixtureHtml.includes('name="robots"'), 'public static page must remain indexable');
      assert.ok(
        fixtureHtml.includes('gtag/js?id=G-TEST') &&
          fixtureHtml.includes('GTM-TEST') &&
          fixtureHtml.includes('TEST-PIXEL'),
        'public tracking is rendered when explicitly enabled',
      );
      assert.ok(
        fixtureHtml.includes("window.gtag('consent', 'default'"),
        'existing consent initialization is preserved',
      );
      assert.ok(
        fixtureHtml.includes('summary_large_image') &&
          fixtureHtml.includes('https://www.aascmed.com/og-images/fixture.jpg'),
      );
      assert.ok(
        !fixtureHtml.includes('<script>untrusted</script>'),
        'authored JSON-LD cannot create executable markup',
      );
      const fixtureJson = fixtureHtml.match(
        /<script type="application\/ld\+json">([\s\S]*?)<\/script>/,
      )?.[1];
      assert.equal(JSON.parse(fixtureJson).name, '</script><script>untrusted</script>');
      const browser = await chromium.launch();
      try {
        const context = await browser.newContext();
        // Run real inline tracking code, but intercept every external request.
        await context.route('**/*', (route) =>
          route.fulfill({ status: 200, contentType: 'application/javascript', body: '' }),
        );
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', (error) => errors.push(error.message));
        await page.setContent(fixtureHtml, { waitUntil: 'load' });
        assert.equal(
          await page.locator('body').evaluate((body) => getComputedStyle(body).margin),
          '0px',
          'shared site styles are rendered without client hydration',
        );
        const tracking = await page.evaluate(() => ({
          tagManager: window.dataLayer.some((item) => item['gtm.start']),
          pixel: window.fbq.queue.map((item) => [...item]),
          commands: window.dataLayer
            .filter((item) => typeof item[0] === 'string')
            .map((item) => Array.from(item)),
          analyticsDate: window.dataLayer.find((item) => item[0] === 'js')?.[1] instanceof Date,
        }));
        assert.deepEqual(
          tracking.commands.map((command) => command[0]),
          ['consent', 'consent', 'js', 'config'],
          'consent precedes one Analytics initialization when GA and GTM are both configured',
        );
        assert.deepEqual(tracking.commands.at(-1), ['config', 'G-TEST']);
        assert.ok(tracking.analyticsDate, 'Analytics startup includes its timestamp');
        assert.ok(tracking.tagManager, 'GTM initialization executes');
        assert.deepEqual(tracking.pixel, [
          ['init', 'TEST-PIXEL'],
          ['track', 'PageView'],
        ]);
        assert.deepEqual(
          errors,
          [],
          'enabled tracking scripts execute together without lexical collisions',
        );
        for (const trackingCase of trackingCases) {
          const html = await readFile(
            path.join(staticOutputDir, trackingCase.name, 'index.html'),
            'utf8',
          );
          const trackingPage = await context.newPage();
          trackingPage.on('pageerror', (error) => errors.push(error.message));
          await trackingPage.setContent(html, { waitUntil: 'load' });
          const state = await trackingPage.evaluate(() => ({
            commands: (window.dataLayer || [])
              .filter((item) => typeof item[0] === 'string')
              .map((item) => Array.from(item)),
            analyticsDate:
              (window.dataLayer || []).find((item) => item[0] === 'js')?.[1] instanceof Date,
            tagManager: (window.dataLayer || []).some((item) => item.event === 'gtm.js'),
          }));
          if (trackingCase.name === 'analytics-only') {
            assert.deepEqual(
              state.commands.map((command) => command[0]),
              ['consent', 'consent', 'js', 'config'],
            );
            assert.deepEqual(
              state.commands.at(-1),
              ['config', 'G-ONLY'],
              'a measurement ID initializes Analytics without a GTM container',
            );
            assert.ok(state.analyticsDate);
            assert.equal(state.tagManager, false);
            assert.equal(
              await trackingPage.locator('script[src*="/gtag/js?id=G-ONLY"]').count(),
              1,
            );
          } else if (trackingCase.name === 'tag-manager-only') {
            assert.deepEqual(
              state.commands.map((command) => command[0]),
              ['consent', 'consent'],
            );
            assert.equal(state.tagManager, true);
            assert.equal(await trackingPage.locator('script[src*="/gtag/js"]').count(), 0);
          } else {
            assert.deepEqual(state.commands, []);
            assert.equal(state.tagManager, false);
            assert.equal(
              await trackingPage.locator('script[src*="googletagmanager.com"]').count(),
              0,
            );
          }
          await trackingPage.close();
        }
        assert.deepEqual(
          errors,
          [],
          'all supported tracking configurations execute without errors',
        );
      } finally {
        await browser.close();
      }
      const notFoundHtml = await readFile(path.join(staticOutputDir, '404.html'), 'utf8');
      assert.ok(notFoundHtml.includes('name="robots" content="noindex, nofollow"'));
      assert.ok(notFoundHtml.includes('Page Not Found!'));
      for (const asset of [
        'assets/favicon/favicon.svg',
        'assets/favicon/favicon-32x32.png',
        'assets/forms/patient_information.pdf',
        'assets/forms/financial_policy.pdf',
        '404.html',
        '_redirects',
        '_headers',
        'sitemap-index.xml',
        'sitemap-0.xml',
      ]) {
        await stat(path.join(staticOutputDir, asset));
      }
      const staticSitemap = await readFile(path.join(staticOutputDir, 'sitemap-0.xml'), 'utf8');
      assertSitemapMetadata(staticSitemap);
      assert.ok(
        staticSitemap.includes('https://www.aascmed.com/verification-document-fixture/'),
        'Astro discovers fixed pages automatically',
      );
      assert.ok(!staticSitemap.includes('/404'), 'Astro excludes the error page');
      const indexXml = await readFile(path.join(staticOutputDir, 'sitemap-index.xml'), 'utf8');
      assert.ok(indexXml.includes('https://www.aascmed.com/sitemap-0.xml'));
      await runBuild('astro.config.ssr.ts');
      const portProbe = await new Promise((resolve) => {
        const server = createServer();
        server.listen(0, '127.0.0.1', () => {
          const { port } = server.address();
          server.close(() => resolve(port));
        });
      });
      app = spawn(process.execPath, ['dist-ssr/server/entry.mjs'], {
        env: {
          ...process.env,
          HOST: '127.0.0.1',
          PORT: String(portProbe),
          PREVIEW_FRAME_ORIGINS: 'https://editor.example.test:8443',
          GATSBY_STRAPI_API_URL: cmsUrl,
          STRAPI_TOKEN: fixtureToken,
          ASTRO_CONTENT_MODE: 'published',
        },
        cwd: astroRoot,
        stdio: 'ignore',
      });
      const base = `http://127.0.0.1:${portProbe}`;
      let response;
      for (let attempt = 0; attempt < 60; attempt++) {
        try {
          response = await fetch(`${base}/verification-document-fixture/`, {
            redirect: 'manual',
          });
          break;
        } catch {
          await new Promise((resolve) => setTimeout(resolve, 250));
        }
      }
      assert.ok(response, 'SSR app starts');
      assert.equal(response.status, 200);
      const ssrHtml = await response.text();
      assert.ok(ssrHtml.includes('name="robots" content="noindex, nofollow"'));
      assert.ok(response.headers.get('x-robots-tag')?.includes('noindex'));
      assert.ok(response.headers.get('cache-control')?.includes('no-store'));
      const framePolicy = response.headers.get('content-security-policy');
      assert.ok(framePolicy?.includes(new URL(cmsUrl).origin));
      assert.ok(framePolicy?.includes('https://editor.example.test:8443'));
      assert.ok(!framePolicy?.includes('strapiapp.com'));
      assert.ok(
        !ssrHtml.includes('googletagmanager.com') && !ssrHtml.includes('connect.facebook.net'),
        'preview omits tracking',
      );
      assert.ok(
        !/G-TEST|GTM-TEST|TEST-PIXEL|googletagmanager\.com|facebook\.net/.test(ssrHtml),
        'preview suppresses tracking even when the route enables it',
      );
      assert.ok(
        ssrHtml.includes('type="application/ld+json"') &&
          ssrHtml.indexOf('application/ld+json') < ssrHtml.indexOf('</head>'),
        'document metadata is rendered in the server response head',
      );
      for (const trackingCase of trackingCases) {
        const preview = await fetch(`${base}/${trackingCase.name}/`);
        assert.equal(preview.status, 200);
        assert.doesNotMatch(
          await preview.text(),
          /googletagmanager\.com|window\.gtag|window\.dataLayer/,
          'preview omits both the Google scripts and their initialization',
        );
      }
      const homepageResponse = await fetch(base);
      assert.equal(homepageResponse.status, 200, 'the real homepage is served');
      assert.ok((await homepageResponse.text()).includes('PUBLISHED HERO'));
      const missing = await fetch(`${base}/unknown-public-route/`);
      assert.equal(missing.status, 404);
      const asset = await fetch(`${base}/assets/forms/patient_information.pdf`);
      assert.equal(asset.status, 200);
      assert.match(asset.headers.get('content-type') || '', /pdf/);
      const beforeSsrRequests = observedCmsRequests.length;
      const sitemapResponse = await fetch(`${base}/sitemap-0.xml`);
      assert.equal(sitemapResponse.status, 200);
      assert.match(sitemapResponse.headers.get('content-type') || '', /(?:application|text)\/xml/);
      assertSitemapMetadata(await sitemapResponse.text());
      assert.equal((await fetch(`${base}/sitemap-index.xml`)).status, 200);
      assert.equal(
        observedCmsRequests.length,
        beforeSsrRequests,
        'the Node adapter serves generated sitemaps without request-time CMS reads',
      );
      assert.ok(
        observedCmsRequests.every((url) => url.query.status === 'published'),
        'static and preview sitemaps are built from published content only',
      );
    } finally {
      if (app?.exitCode === null && app.signalCode === null) {
        const exited = new Promise((resolve) => app.once('exit', resolve));
        app.kill();
        await exited;
      }
      await cms.close();
      for (const file of trackingFixtures) {
        await unlink(file);
      }
      if (fixtureCreated) {
        await unlink(fixturePath);
      }
    }
  },
);
